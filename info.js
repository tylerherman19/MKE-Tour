"All Saints’ Cathedral, one of the first Episcopal cathedrals in the nation, is also one of Milwaukee’s oldest houses of worship, being in continuous use since 1871.  The Cathedral campus consists of a high-steepled church, guild hall, and bishop’s manse arranged in a U-shape around a leafy churchyard.  The three buildings, built between 1868 and 1903, reflect the determination of Gilded Age people to build up the faith in what was then a new, rapidly growing city.  All Saints is notable for the architectural integrity of its compound, preserved intact for over a century.",
"The Gothic Revival church, designed by the prolific Edward Townsend Mix, was originally built as a Congregational church but purchased by the Episcopalians soon after its completion. Its interior was initially plain.  Successive embellishments over the decades, including extensive wood carving and a harmonious ensemble of largely English-made stained glass windows, capture changing ideas about glorifying God and expressing the sacred nature of an ancient sacramental faith.  The focal point of the interior is the high altar, surmounted by a magnificent bas-relief triptych and reredos.  Designed by Eugene W. Mason Jr of the New York firm of Carriere & Hastings, it was installed in 1923.  The Cathedral’s chief external feature is its two-hundred-foot-tall spire, housing a massive bronze bell cast in 1867.  Five more bells were added in 2007, as “Bells of Remembrance” to ring daily in memory of those who died on 9-11 and in subsequent terror attacks.  The Bells of Remembrance and Hope for 9-11 ring at the end of the Angelus daily at noon and 6pm.  A nine bell pattern is struck eleven times.",
